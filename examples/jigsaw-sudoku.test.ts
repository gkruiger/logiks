import { expect, test } from 'vitest'

import { Sudoku } from './sudoku'

test('Jigsaw', () => {

  const solutionFound = new Sudoku([
    [ , 7, 4, 9,  ,  , 3,  ,  ,],
    [8,  , 6, 4, 5, 7,  , 2,  ,],
    [ ,  ,  , 8,  ,  , 7,  , 4,],
    [ , 8,  , 7,  ,  ,  ,  ,  ,],
    [ ,  ,  ,  ,  , 8,  ,  1  ,],
    [9,  ,  ,  ,  , 4, 6,  ,  ,],
    [ , 3,  , 1, 8, 9, 2,  ,  ,],
    [ ,  , 7,  , 6, 1,  ,  ,  ,],
    [ ,  ,  , 2, 4, 3,  ,  ,  ,]
  ], [
    [1, 1, 1, 1, 1, 2, 2, 3, 3 ],
    [1, 1, 4, 4, 4, 2, 2, 3, 3 ],
    [1, 1, 4, 4, 4, 2, 3, 3, 3 ],
    [5, 5, 4, 4, 4, 2, 2, 3, 3 ],
    [5, 5, 5, 5, 5, 2, 2, 7, 7 ],
    [6, 6, 6, 5, 5, 8, 8, 7, 7 ],
    [6, 6, 9, 9, 9, 8, 8, 7, 7 ],
    [6, 6, 9, 9, 9, 8, 7, 7, 7 ],
    [6, 6, 9, 9, 9, 8, 8, 8, 8 ],
  ])

  const solution = [
    [ 6, 7, 4, 9, 2, 5, 3, 8, 1 ],
    [ 8, 1, 6, 4, 5, 7, 9, 2, 3 ],
    [ 3, 5, 1, 8, 9, 2, 7, 6, 4 ],
    [ 4, 8, 2, 7, 3, 6, 1, 5, 9 ],
    [ 2, 9, 3, 6, 7, 8, 4, 1, 5 ],
    [ 9, 2, 8, 5, 1, 4, 6, 3, 7 ],
    [ 7, 3, 5, 1, 8, 9, 2, 4, 6 ],
    [ 5, 4, 7, 3, 6, 1, 8, 9, 2 ],
    [ 1, 6, 9, 2, 4, 3, 5, 7, 8 ]
  ]

  expect(solutionFound).toStrictEqual(solution)
})