import { expect, test } from 'vitest'

import { Futoshiki } from './futoshiki'

test('Futoshiki', () => {

  const solutionFound = new Futoshiki([
    [ ' ', ' ', ' ', ' ', ' ', ' ', ' ', ' ',' ' ],
    [ ' ', ' ', ' ', ' ', ' ', ' ', 'v', ' ',' ' ],
    [ ' ', ' ', ' ', ' ', ' ', ' ', ' ', ' ',' ' ],
    [ ' ', ' ', ' ', ' ', ' ', ' ', 'v', ' ',' ' ],
    [ ' ', ' ', ' ', '<', '3', ' ', ' ', ' ',' ' ],
    [ ' ', ' ', ' ', ' ', ' ', ' ', ' ', ' ',' ' ],
    [ ' ', ' ', ' ', ' ', ' ', ' ', ' ', ' ',' ' ],
    [ ' ', ' ', ' ', ' ', 'v', ' ', ' ', ' ','v' ],
    [ ' ', '>', ' ', '>', ' ', '>', ' ', ' ',' ' ],
  ])

  const solution = [
    [ 2, 3, 4, 5, 1 ],
    [ 3, 5, 1, 4, 2 ],
    [ 4, 1, 3, 2, 5 ],
    [ 1, 2, 5, 3, 4 ],
    [ 5, 4, 2, 1, 3 ],
  ]

  expect(solutionFound).toStrictEqual(solution)
})
